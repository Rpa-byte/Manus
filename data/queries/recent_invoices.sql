WITH RankedInvoices AS (
    SELECT
        L.NUM_0,
        L.ACCDAT_0,
        L.PTHNUM_0,
        L.POHNUM_0,
        I.ITMDES1_0,
        R.XRET_0,
        ROW_NUMBER() OVER (
            PARTITION BY L.NUM_0
            ORDER BY L.ACCDAT_0 DESC
        ) AS RN
    FROM x3.BASE1.XLISTVENTER2 AS L
    LEFT JOIN x3.BASE1.ITMMASTER AS I
        ON L.EANCOD_0 = I.EANCOD_0
    LEFT JOIN x3.BASE1.XRETCLI AS R
        ON L.BPRNAM_0 = R.BPR_0
    WHERE L.ACCDAT_0 >= DATEADD(DAY, -30, CAST(GETDATE() AS DATE))
      AND L.ACCDAT_0 < DATEADD(DAY, 1, CAST(GETDATE() AS DATE))
)
SELECT *
FROM RankedInvoices
WHERE RN = 1
ORDER BY ACCDAT_0 DESC;